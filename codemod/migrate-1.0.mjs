const NAME = '[a-z0-9]+(?:-[a-z0-9]+)*';

/**
 * A utility of a theme color, type-ramp step or shadow level: the root and the name, then what
 * may follow a class (a modifier, an important mark, a delimiter). Before it: the start, a
 * delimiter, a variant's colon or an important mark; never part of a longer class or selector.
 */
const UTILITY = new RegExp(
  String.raw`(?<![\w\-./#@$%\\\[])(${COLOR_ROOTS.map((root) => root.replace('-', '\\-')).join('|')})-(${NAME})` +
    String.raw`(?=(?:\/(?:[\w.%]+|\[[^\]\s]*\]|\([^)\s]*\)))?!?(?![\w\-\[(])(?!\.\w))`,
  'g',
);

/**
 * A use of a theme variable (`--color-primary`, `--text-body-1--line-height`), never its
 * declaration (`--color-primary: …`, `'--color-primary': …`) or registration (`@property`).
 */
const VARIABLE = new RegExp(
  String.raw`(?<![\w-])(?<!@property\s+)--(color|text|shadow)-(${NAME})((?:--[a-z]+(?:-[a-z]+)*)?)(?![\w-])(?!\s*['"]?\s*:)`,
  'g',
);

/** A declaration of a theme key (`--color-success: …`, `'--text-body-1': …`), by namespace. */
const DECLARATION = new RegExp(
  String.raw`(?<![\w-])--(color|text|shadow)-(${NAME})(?:--[a-z]+(?:-[a-z]+)*)?['"]?\s*:`,
  'g',
);

/**
 * The theme keys of Wave's names that `texts` (an app's files) declare themselves (an `@theme`
 * with `--color-success: …`, DaisyUI's or Bootstrap's `success`, `error`, `info`): those names are
 * the app's own, so their utilities are left alone like the shadcn/ui names (`--include-shared`
 * rewrites them). By namespace: `{ color, text, shadow }`, each a sorted array.
 */
export function declaredNames(texts) {
  const known = { color: THEME_TABLE.colors, text: THEME_TABLE.text, shadow: THEME_TABLE.shadow };
  const found = { color: new Set(), text: new Set(), shadow: new Set() };
  for (const text of texts) {
    for (const [, namespace, name] of text.matchAll(DECLARATION)) {
      if (known[namespace].includes(name)) found[namespace].add(name);
    }
  }
  return Object.fromEntries(Object.entries(found).map(([key, set]) => [key, [...set].sort()]));
}

/**
 * Rewrites the utilities and variable uses of one piece of text; `classes: false` rewrites the
 * variable uses only (a CSS rule outside `@apply`, a `style` attribute), `variables: false` the
 * utilities only (an object key: `{ '--color-x': … }` is a declaration). A name of
 * SHARED_COLORS, or one `appNames` lists (see declaredNames), is rewritten only with
 * `includeShared`. A class with Wave's utility prefix is left alone; `prefixedLead` says that the
 * text starts inside one (template text after a substitution, `wave:${gate}bg-primary`). Counts
 * each rewrite and each shared use left alone in `stats`.
 */
export function rewriteText(
  text,
  {
    includeShared = false,
    classes = true,
    variables = true,
    appNames,
    stats,
    prefixedLead = false,
  } = {},
) {
  const colors = new Set(THEME_TABLE.colors);
  const steps = new Set(THEME_TABLE.text);
  const levels = new Set(THEME_TABLE.shadow);
  const shared = {
    color: new Set([...SHARED_COLORS, ...(appNames?.color ?? [])]),
    text: new Set(appNames?.text ?? []),
    shadow: new Set(appNames?.shadow ?? []),
  };
  /** Whether a known name is rewritten: a shared one only with `includeShared` (counted). */
  const rewrites = (name, namespace) => {
    if (shared[namespace].has(name) && !includeShared) {
      if (stats) stats.shared += 1;
      return false;
    }
    if (stats) stats.replacements += 1;
    return true;
  };
  let out = text;
  if (classes) {
    out = out.replace(UTILITY, (match, root, name, offset, whole) => {
      // A class with Wave's own prefix (`wave:bg-primary`, `wave:hover:text-body-1`) is a class of
      // the library's 1.0 namespace, never an app's 0.x one: Tailwind puts the prefix first.
      if (prefixedClass(whole, offset, prefixedLead)) return match;
      // The type ramp and the shadow levels share no name with the colors.
      const namespace =
        root === 'text' && steps.has(name)
          ? 'text'
          : root === 'shadow' && levels.has(name)
            ? 'shadow'
            : colors.has(name)
              ? 'color'
              : null;
      if (!namespace) return match;
      return rewrites(name, namespace) ? `${root}-wave-${name}` : match;
    });
  }
  if (!variables) return out;
  return out.replace(VARIABLE, (match, namespace, name, sub) => {
    const known =
      namespace === 'color'
        ? colors.has(name) && !sub
        : namespace === 'text'
          ? steps.has(name)
          : levels.has(name) && !sub;
    if (!known) return match;
    return rewrites(name, namespace) ? `--${namespace}-wave-${name}${sub}` : match;
  });
}

/**
 * Where the class that holds `text[offset]` starts: after the whitespace or quote before it (a
 * class holds neither), or at the start of the text.
 */
function classStart(text, offset) {
  let start = offset;
  while (start > 0 && !/[\s'"`]/.test(text[start - 1])) start -= 1;
  return start;
}

/**
 * Whether the class that holds `text[offset]` carries Wave's utility prefix: it starts with
 * `wave:`, or it starts the text and `lead` says the text continues a prefixed class.
 */
function prefixedClass(text, offset, lead) {
  const start = classStart(text, offset);
  return (start === 0 && lead) || text.startsWith('wave:', start);
}

/** Replaces the given `[start, end)` ranges of `text` by `rewrite(piece)`. */
function rewriteRanges(text, ranges, rewrite) {
  let out = '';
  let last = 0;
  for (const [start, end] of ranges) {
    out += text.slice(last, start) + rewrite(text.slice(start, end));
    last = end;
  }
  return out + text.slice(last);
}

const REGEX_BEFORE = new Set([...'(,=:[!&|?{};+-*%<>~^']);
const REGEX_KEYWORDS =
  /(?:^|[^\w$])(?:return|typeof|case|do|else|in|of|new|delete|void|throw|yield|await)$/;

/**
 * The `[start, end)` ranges of a script's string literals and template-literal text, outside
 * comments and regular expressions (a quote right after a letter or digit, an apostrophe of JSX
 * text, opens none).
 */
export function scriptStringRanges(code) {
  const ranges = [];
  const stack = []; // open template substitutions: the brace depth to return at
  let depth = 0;
  let i = 0;
  let previous = ''; // the last significant character of code
  let word = ''; // the identifier or keyword that ends at `previous`
  const template = () => {
    // In a template's text, from `i`; returns when it ends or a substitution opens.
    const start = i;
    for (; i < code.length; i++) {
      if (code[i] === '\\') i++;
      else if (code[i] === '`') {
        ranges.push([start, i]);
        i++;
        return false;
      } else if (code[i] === '$' && code[i + 1] === '{') {
        ranges.push([start, i]);
        i += 2;
        return true;
      }
    }
    ranges.push([start, code.length]);
    return false;
  };
  while (i < code.length) {
    const ch = code[i];
    if (ch === '/' && code[i + 1] === '/') {
      const end = code.indexOf('\n', i);
      i = end === -1 ? code.length : end;
      continue;
    }
    if (ch === '/' && code[i + 1] === '*') {
      const end = code.indexOf('*/', i + 2);
      i = end === -1 ? code.length : end + 2;
      continue;
    }
    if (/\s/.test(ch)) {
      i++;
      continue;
    }
    if (ch === "'" || ch === '"') {
      if (/[\w$]/.test(code[i - 1] ?? '')) {
        // An apostrophe of JSX text (`Don't`): no string.
        i++;
        continue;
      }
      const start = i + 1;
      let j = start;
      while (j < code.length && code[j] !== ch && code[j] !== '\n') j += code[j] === '\\' ? 2 : 1;
      ranges.push([start, Math.min(j, code.length)]);
      i = j + 1;
      previous = ch;
      word = '';
      continue;
    }
    if (ch === '`') {
      i++;
      if (template()) stack.push(depth);
      previous = '`';
      word = '';
      continue;
    }
    if (ch === '/') {
      const regex =
        code[i - 1] !== '<' &&
        code[i + 1] !== '>' &&
        (previous === '' || REGEX_BEFORE.has(previous) || REGEX_KEYWORDS.test(word));
      if (regex) {
        let j = i + 1;
        let inClass = false;
        for (; j < code.length && code[j] !== '\n'; j++) {
          if (code[j] === '\\') j++;
          else if (code[j] === '[') inClass = true;
          else if (code[j] === ']') inClass = false;
          else if (code[j] === '/' && !inClass) break;
        }
        i = j + 1;
        while (/[a-z]/i.test(code[i] ?? '')) i++;
        previous = '/';
        word = '';
        continue;
      }
    }
    if (ch === '{') depth++;
    if (ch === '}') {
      if (stack.length > 0 && stack[stack.length - 1] === depth) {
        stack.pop();
        i++;
        if (template()) stack.push(depth);
        previous = '`';
        word = '';
        continue;
      }
      depth--;
    }
    if (/[\w$]/.test(ch)) {
      let j = i;
      while (j < code.length && /[\w$]/.test(code[j])) j++;
      word = code.slice(i, j);
      previous = code[j - 1];
      i = j;
      continue;
    }
    previous = ch;
    word = '';
    i++;
  }
  return ranges;
}

/**
 * Whether the string at `[start, end)` of `code` (its text, without the quotes) is an object key:
 * after `{` or `,` and before `:`. A key holds classes (`{ 'bg-success': on }`) but never a
 * variable use: `{ '--color-success': x }` declares it.
 */
function isObjectKey(code, start, end) {
  const before = code.slice(0, start - 1).trimEnd();
  return /[{,]$/.test(before) && /^\s*:/.test(code.slice(end + 1));
}

/** Rewrites a script: its string and template text only. */
export function rewriteScript(code, options) {
  const ranges = scriptStringRanges(code);
  let out = '';
  let last = 0;
  // Whether the template text that ends at `last` ends inside a prefixed class, which continues
  // after a substitution (`wave:${gate}bg-primary`, the gate a chain of variants).
  let lead = false;
  for (const [start, end] of ranges) {
    const piece = code.slice(start, end);
    const key = isObjectKey(code, start, end);
    const continued = lead && code.startsWith('${', last) && code[start - 1] === '}';
    out +=
      code.slice(last, start) +
      rewriteText(piece, {
        ...options,
        ...(key ? { variables: false } : {}),
        prefixedLead: continued,
      });
    lead = prefixedClass(piece, piece.length, continued);
    last = end;
  }
  return out + code.slice(last);
}

/** Rewrites a stylesheet: `@apply` lists, and variable uses outside comments. */
export function rewriteStyle(css, options) {
  const comments = [...css.matchAll(/\/\*[\s\S]*?\*\//g)].map((m) => [
    m.index,
    m.index + m[0].length,
  ]);
  const ranges = [];
  let last = 0;
  for (const [start, end] of comments) {
    ranges.push([last, start]);
    last = end;
  }
  ranges.push([last, css.length]);
  return rewriteRanges(css, ranges, (piece) => {
    const applied = piece.replace(/@apply\b[^;}]*/g, (list) => rewriteText(list, options));
    return rewriteText(applied, { ...options, classes: false });
  });
}

/** The value of an attribute that starts at `i` (a quote or a brace): its range and end. */
function attributeValue(text, i) {
  const open = text[i];
  if (open === '"' || open === "'") {
    const end = text.indexOf(open, i + 1);
    return end === -1 ? null : { start: i + 1, end, next: end + 1 };
  }
  if (open === '{') {
    let depth = 0;
    for (let j = i; j < text.length; j++) {
      const ch = text[j];
      if (ch === '"' || ch === "'" || ch === '`') {
        const close = text.indexOf(ch, j + 1);
        if (close === -1) return null;
        j = close;
      } else if (ch === '{') depth++;
      else if (ch === '}' && --depth === 0) return { start: i + 1, end: j, next: j + 1 };
    }
  }
  return null;
}

const CLASS_ATTRIBUTE =
  /(?<=[\s<])(?:class|className|:class|v-bind:class|class:list|\[class\]|\[ngClass\]|ngClass)\s*=\s*(?=["'{])/g;
const STYLE_ATTRIBUTE = /(?<=[\s<])(?::style|v-bind:style|style)\s*=\s*(?=["'{])/g;

/** Rewrites a markup file: class and style attributes, script and style blocks (see the header). */
export function rewriteMarkup(text, options, { mdx = false } = {}) {
  // The parts never read: comments, and the fenced code of MDX.
  const skipped = [...text.matchAll(/<!--[\s\S]*?-->/g)].map((m) => [
    m.index,
    m.index + m[0].length,
  ]);
  if (mdx) {
    for (const m of text.matchAll(/^(\s*)(```|~~~)[^\n]*\n[\s\S]*?^\1\2[^\n]*$/gm)) {
      skipped.push([m.index, m.index + m[0].length]);
    }
  }
  const inSkipped = (index) => skipped.some(([start, end]) => index >= start && index < end);
  const edits = [];
  const blocks = [];
  for (const m of text.matchAll(/<(script|style)\b[^>]*>([\s\S]*?)<\/\1\s*>/gi)) {
    if (inSkipped(m.index)) continue;
    const start = m.index + m[0].indexOf('>') + 1;
    const end = start + m[2].length;
    blocks.push([m.index, m.index + m[0].length]);
    const body = text.slice(start, end);
    const next =
      m[1].toLowerCase() === 'script' ? rewriteScript(body, options) : rewriteStyle(body, options);
    if (next !== body) edits.push([start, end, next]);
  }
  const free = (index) => !inSkipped(index) && !blocks.some(([s, e]) => index >= s && index < e);
  for (const [pattern, classes] of [
    [CLASS_ATTRIBUTE, true],
    [STYLE_ATTRIBUTE, false],
  ]) {
    for (const m of text.matchAll(pattern)) {
      if (!free(m.index)) continue;
      const value = attributeValue(text, m.index + m[0].length);
      if (!value) continue;
      const piece = text.slice(value.start, value.end);
      const next = classes
        ? text[value.start - 1] === '{'
          ? rewriteScript(piece, options)
          : rewriteText(piece, options)
        : rewriteText(piece, { ...options, classes: false });
      if (next !== piece) edits.push([value.start, value.end, next]);
    }
  }
  // Svelte's class directive: `class:bg-primary={active}`.
  for (const m of text.matchAll(/(?<=\sclass:)([^\s=/>]+)/g)) {
    if (!free(m.index)) continue;
    const next = rewriteText(m[1], options);
    if (next !== m[1]) edits.push([m.index, m.index + m[1].length, next]);
  }
  edits.sort((a, b) => a[0] - b[0]);
  let out = '';
  let last = 0;
  for (const [start, end, next] of edits) {
    if (start < last) continue;
    out += text.slice(last, start) + next;
    last = end;
  }
  return out + text.slice(last);
}

/** Rewrites a file's text by its extension; `undefined` for a type the codemod does not read. */
export function rewriteFile(path, text, options) {
  const extension = extname(path).toLowerCase();
  if (EXTENSIONS.script.includes(extension)) return rewriteScript(text, options);
  if (EXTENSIONS.style.includes(extension)) return rewriteStyle(text, options);
  if (EXTENSIONS.markup.includes(extension)) {
    return rewriteMarkup(text, options, { mdx: extension === '.mdx' });
  }
  return undefined;
}

