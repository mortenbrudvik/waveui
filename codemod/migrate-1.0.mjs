const SKIPPED_DIRECTORIES = new Set(['node_modules', '.git']);
const readable = (path) =>
  Object.values(EXTENSIONS).some((list) => list.includes(extname(path).toLowerCase()));

/** A glob as a regular expression over forward-slash paths. */
export function globToRegExp(glob) {
  let out = '';
  for (let i = 0; i < glob.length; i++) {
    const ch = glob[i];
    if (ch === '*' && glob[i + 1] === '*') {
      i++;
      if (glob[i + 1] === '/') {
        i++;
        out += '(?:.*/)?';
      } else out += '.*';
    } else if (ch === '*') out += '[^/]*';
    else if (ch === '?') out += '[^/]';
    else if (ch === '{') {
      const end = glob.indexOf('}', i);
      if (end === -1) out += '\\{';
      else {
        out += `(?:${glob
          .slice(i + 1, end)
          .split(',')
          .map((part) => globToRegExp(part).source.slice(1, -1))
          .join('|')})`;
        i = end;
      }
    } else if (ch === '[') {
      const end = glob.indexOf(']', i);
      if (end === -1) out += '\\[';
      else {
        out += `[${glob.slice(i + 1, end).replace(/^!/, '^')}]`;
        i = end;
      }
    } else out += /[\\^$.|+()]/.test(ch) ? `\\${ch}` : ch;
  }
  return new RegExp(`^${out}$`);
}

/** Every readable file under `directory`, skipping node_modules and .git. */
function walk(directory, found) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (SKIPPED_DIRECTORIES.has(entry.name)) continue;
    const path = join(directory, entry.name);
    if (entry.isDirectory()) walk(path, found);
    else if (entry.isFile() && readable(path)) found.add(path);
  }
}

/**
 * The files of `inputs` (paths or globs, relative to `cwd`), sorted; `notes` gets why an input
 * added nothing. A path inside node_modules is never taken.
 */
export function collectFiles(inputs, cwd = process.cwd(), notes = []) {
  const found = new Set();
  for (const input of inputs) {
    const normalized = input.split(sep).join('/');
    if (normalized.split('/').includes('node_modules')) {
      notes.push(`${input}: node_modules is never migrated`);
      continue;
    }
    const before = found.size;
    if (/[*?[{]/.test(normalized)) {
      const segments = normalized.split('/');
      const index = segments.findIndex((segment) => /[*?[{]/.test(segment));
      const base = resolve(cwd, segments.slice(0, index).join('/') || '.');
      const pattern = globToRegExp(segments.slice(index).join('/'));
      const all = new Set();
      try {
        walk(base, all);
      } catch {
        // A base directory that does not exist matches nothing.
      }
      for (const path of all) {
        if (pattern.test(relative(base, path).split(sep).join('/'))) found.add(path);
      }
    } else {
      const path = resolve(cwd, input);
      let stat;
      try {
        stat = statSync(path);
      } catch {
        notes.push(`${input}: not found`);
        continue;
      }
      if (stat.isDirectory()) walk(path, found);
      else if (readable(path)) found.add(path);
      else notes.push(`${input}: not a file type the codemod reads`);
    }
    if (found.size === before && !notes.some((note) => note.startsWith(`${input}:`))) {
      notes.push(`${input}: matched no file`);
    }
  }
  return [...found].sort();
}

/** The changed lines of a file, for the dry run's report: `[line, before, after]`. */
function changedLines(before, after) {
  const a = before.split('\n');
  const b = after.split('\n');
  const lines = [];
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] !== b[i]) lines.push([i + 1, a[i] ?? '', b[i] ?? '']);
  }
  return lines;
}

