const USAGE =
  'usage: node node_modules/@mortenbrudvik/waveui/codemod/migrate-1.0.mjs [--include-shared] ' +
  '[--dry-run] <globs or paths>...';

/** Runs the codemod; returns the exit code. `io` takes `log` and `error`. */
export function main(argv = process.argv.slice(2), { cwd = process.cwd(), io = console } = {}) {
  const options = { includeShared: false, dryRun: false, inputs: [] };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--include-shared') options.includeShared = true;
    else if (arg === '--dry-run') options.dryRun = true;
    else if (arg === '--print-table') {
      const file = argv[i + 1];
      if (!file) {
        io.error('migrate-1.0: --print-table needs the path of tokens.css');
        return 2;
      }
      io.log(printTable(parseThemeTable(readFileSync(resolve(cwd, file), 'utf8'))).trimEnd());
      return 0;
    } else if (arg === '--help' || arg === '-h') {
      io.log(USAGE);
      return 0;
    } else if (arg.startsWith('--')) {
      io.error(`migrate-1.0: unknown option ${arg}\n${USAGE}`);
      return 2;
    } else options.inputs.push(arg);
  }
  if (options.inputs.length === 0) {
    io.error(`migrate-1.0: no files or globs given\n${USAGE}`);
    return 2;
  }

  const notes = [];
  const files = collectFiles(options.inputs, cwd, notes);
  for (const note of notes) io.log(`migrate-1.0: ${note}`);
  if (files.length === 0) {
    io.error('migrate-1.0: no file to migrate');
    return 1;
  }
  const stats = { replacements: 0, shared: 0 };
  let changed = 0;
  let failed = 0;
  const texts = new Map();
  for (const file of files) {
    try {
      texts.set(file, readFileSync(file, 'utf8'));
    } catch (error) {
      io.error(`migrate-1.0: cannot read ${file}: ${error.message}`);
      failed++;
    }
  }
  // Wave's names that the app declares as its own theme keys are the app's.
  const appNames = declaredNames(texts.values());
  const declared = [
    ...appNames.color.map((name) => `--color-${name}`),
    ...appNames.text.map((name) => `--text-${name}`),
    ...appNames.shadow.map((name) => `--shadow-${name}`),
  ];
  if (declared.length > 0) {
    io.log(
      `migrate-1.0: the files declare ${declared.join(', ')}: ` +
        (options.includeShared
          ? 'rewritten as Wave’s all the same (--include-shared)'
          : 'the app’s own names, left as they are (--include-shared rewrites them too)'),
    );
  }
  for (const [file, text] of texts) {
    const next = rewriteFile(file, text, {
      includeShared: options.includeShared,
      appNames,
      stats,
    });
    if (next === undefined || next === text) continue;
    changed++;
    const name = relative(cwd, file).split(sep).join('/');
    if (options.dryRun) {
      for (const [line, before, after] of changedLines(text, next)) {
        io.log(`${name}:${line}\n  - ${before.trim()}\n  + ${after.trim()}`);
      }
      continue;
    }
    try {
      writeFileSync(file, next);
    } catch (error) {
      io.error(`migrate-1.0: cannot write ${file}: ${error.message}`);
      failed++;
    }
  }
  io.log(
    `migrate-1.0${options.dryRun ? ' (dry run)' : ''}: ${stats.replacements} replacement(s) in ` +
      `${changed} of ${files.length} file(s)` +
      (stats.shared > 0
        ? `; ${stats.shared} use(s) of a name shared with shadcn/ui${declared.length > 0 ? ' or declared by the app' : ''} ` +
          'left as they are (pass --include-shared if they named Wave’s tokens)'
        : ''),
  );
  return failed > 0 ? 1 : 0;
}

/** Whether this module is the script Node was started with (real paths, so links match). */
function isMain() {
  if (!process.argv[1]) return false;
  try {
    const canonical = (path) => {
      const real = realpathSync(path);
      return process.platform === 'win32' ? real.toLowerCase() : real;
    };
    return canonical(fileURLToPath(import.meta.url)) === canonical(resolve(process.argv[1]));
  } catch {
    return false;
  }
}

if (isMain()) process.exitCode = main();
