/**
 * The namespaced theme keys of Wave's tokens.css (`tokensCss`): the color names (`primary` of
 * `--color-wave-primary`), the type-ramp steps (`body-1`; the `--line-height` and `--font-weight`
 * sub-keys are no utilities) and the shadow levels, in the file's order.
 */
export function parseThemeTable(tokensCss) {
  const css = tokensCss.replace(/\/\*[\s\S]*?\*\//g, '');
  const keys = [];
  for (const match of css.matchAll(/@theme\b[^{]*\{/g)) {
    let depth = 1;
    let i = match.index + match[0].length;
    const start = i;
    for (; i < css.length && depth > 0; i++) {
      if (css[i] === '{') depth++;
      else if (css[i] === '}') depth--;
    }
    // Only the block's own declarations: a nested `@keyframes` holds none of these keys.
    for (const key of css.slice(start, i).matchAll(/(?:^|[;{\s])(--[a-z0-9-]+)\s*:/g)) {
      keys.push(key[1]);
    }
  }
  const after = (namespace) =>
    keys
      .filter((key) => key.startsWith(namespace) && !key.slice(namespace.length).includes('--'))
      .map((key) => key.slice(namespace.length));
  const unique = (list) => [...new Set(list)];
  return {
    colors: unique(after('--color-wave-')),
    text: unique(after('--text-wave-')),
    shadow: unique(after('--shadow-wave-')),
  };
}

/** The THEME_TABLE declaration for `table`, as this file holds it. */
export function printTable(table) {
  const list = (values) => `[${values.map((value) => `'${value}'`).join(', ')}]`;
  return (
    `export const THEME_TABLE = {\n  colors: ${list(table.colors)},\n` +
    `  text: ${list(table.text)},\n  shadow: ${list(table.shadow)},\n};\n`
  );
}

