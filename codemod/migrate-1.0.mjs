#!/usr/bin/env node
/**
 * WaveUI 1.0 migration of an app's own classes: rewrites the utilities that used Wave's former
 * unprefixed theme names to the namespaced ones of 1.0.
 *
 *   bg-primary                 ->  bg-wave-primary
 *   hover:text-foreground/50   ->  hover:text-wave-foreground/50
 *   text-body-1, shadow-4      ->  text-wave-body-1, shadow-wave-4
 *   var(--color-primary)       ->  var(--color-wave-primary)
 *
 * Usage (from the app's root):
 *   node node_modules/@mortenbrudvik/waveui/codemod/migrate-1.0.mjs [--include-shared] [--dry-run]
 *     <globs or paths>...
 *
 *   --dry-run         prints every change as a diff-like report and writes nothing
 *   --include-shared  also rewrites the names a stock shadcn/ui theme defines too (`bg-primary`,
 *                     `text-foreground`, `border-border`, `ring-ring`, … SHARED_COLORS), and the
 *                     names the scanned files declare as their own theme keys (an `@theme` with
 *                     `--color-success: …`, as DaisyUI or Bootstrap themes have `success`,
 *                     `error`, `info`; see declaredNames): in such an app they are the app's own
 *                     classes, so they are left alone (and counted) unless the app used them for
 *                     Wave's tokens. Scan the app's theme CSS with the rest for this to work.
 *
 * Paths are files or directories (walked for the file types below); globs take `*`, `**`, `?`,
 * `{a,b}` and `[…]` (quote them on shells that expand globs themselves). `node_modules` (and
 * `.git`) is never read or written.
 *
 * What it reads, by file type, never a comment:
 *   .js .jsx .ts .tsx .mjs .cjs .mts .cts   string literals and the text of template literals
 *                                           (JSX attribute values included; JSX text is not)
 *   .css                                    `@apply` lists, and theme variable uses everywhere
 *   .html .vue .svelte .mdx                 class attributes (`class`, `className`, `:class`,
 *                                           `v-bind:class`, `class:list`, Svelte's `class:` names),
 *                                           theme variable uses in `style` attributes, and their
 *                                           `<script>` and `<style>` blocks as above (fenced code
 *                                           blocks of MDX are left alone)
 * A utility is rewritten with its variants (`dark:`, `hover:`, `data-[…]:`), its opacity or line
 * height modifier (`/50`), its important mark (`!bg-primary`, `bg-primary!`) and as a negated or
 * arbitrary part of nothing else: `bg-primary-hover` is the token `primary-hover`, `text-wave-body-1`
 * is already migrated (a second run changes nothing), a class with Wave's own utility prefix
 * (`wave:bg-primary`, `wave:hover:text-body-1`, as the library's 1.0 class strings are written) is
 * none of the app's 0.x classes, a word such as `'primary'` is no utility,
 * and neither is a file name (`'bg-success.png'`). A theme variable use (`var(--color-primary)`,
 * `theme(--text-body-1--line-height)`, `bg-(--color-primary)`) is rewritten; a declaration
 * (`--color-primary: …` in an app's own `@theme`, a style object's `'--color-primary': x`) and a
 * registration (`@property --color-primary`) are not.
 *
 * The names come from THEME_TABLE: the namespaced keys of Wave's `tokens.css` (`--color-wave-*`,
 * `--text-wave-*`, `--shadow-wave-*`), generated with `--print-table <tokens.css>` and kept in step
 * by Wave's tests. The font, animation, duration and curve utilities already carried `wave` in 0.x.
 *
 * Exit code: 0 when the run completed (changed or not), 1 when a file could not be read or written
 * or no file matched, 2 on a usage error. Dependency-free: Node.js built-ins only.
 */
